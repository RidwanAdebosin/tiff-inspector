#!/usr/bin/env python3
"""Regenerates test/golden/dune: one text and one JSON golden per fixture."""
import os
import subprocess
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
fixtures = os.path.join(root, "test", "fixtures")
names = sorted(f[:-4] for f in os.listdir(fixtures) if f.endswith(".tif"))
out = ["; Generated by scripts/gen-golden-dune.py. Update outputs with `dune test; dune promote`.\n"]
for n in names:
    for fmt, ext, extra in (("text", "txt", " --tags"), ("json", "json", "")):
        out.append(f"""
(rule
 (deps ../fixtures/{n}.tif)
 (action
  (with-stdout-to {n}.{ext}.out
   (with-stderr-to %{{null}}
   (with-accepted-exit-codes (or 0 1)
    (chdir ../fixtures
     (run %{{bin:tiff-inspector}} inspect --format {fmt}{extra} {n}.tif)))))))

(rule
 (alias runtest)
 (action (diff {n}.{ext} {n}.{ext}.out)))
""")
# Format like `dune build @fmt` expects, so CI's formatting check passes
text = subprocess.run(
    ["dune", "format-dune-file"], input="".join(out), capture_output=True, text=True, check=True
).stdout
with open(os.path.join(root, "test", "golden", "dune"), "w") as f:
    f.write(text)
print(f"wrote rules for {len(names)} fixtures", file=sys.stderr)
